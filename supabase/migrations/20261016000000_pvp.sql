-- 월드랭킹(PvP): 끝없는 전장에 들어선 용사 카드와 대전 기록
-- 쓰기는 서버(submit-run 함수)만, 읽기는 누구나.
create table if not exists public.pvp_cards (
  id          text primary key,
  seed        bigint unique,
  nickname    text not null,
  hero        text not null,
  race        text not null,
  power       bigint not null default 0,
  hp          bigint not null default 100,
  ass         integer not null default 0,
  rev         integer not null default 0,
  bls         integer not null default 0,
  cur         integer not null default 0,
  floor       integer not null default 0,
  fights_done integer not null default 0,
  ladder      double precision not null default 0,
  is_bot      boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists pvp_cards_ladder_idx on public.pvp_cards (ladder desc);

create table if not exists public.pvp_matches (
  id         bigserial primary key,
  attacker   text not null,
  defender   text not null,
  milestone  integer not null,
  win        boolean not null,
  p          double precision not null,
  log        jsonb,
  created_at timestamptz not null default now()
);
create index if not exists pvp_matches_attacker_idx on public.pvp_matches (attacker, id desc);

alter table public.pvp_cards enable row level security;
alter table public.pvp_matches enable row level security;
drop policy if exists "pvp cards readable" on public.pvp_cards;
create policy "pvp cards readable" on public.pvp_cards for select to anon, authenticated using (true);
drop policy if exists "pvp matches readable" on public.pvp_matches;
create policy "pvp matches readable" on public.pvp_matches for select to anon, authenticated using (true);

